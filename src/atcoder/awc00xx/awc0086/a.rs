// https://atcoder.jp/contests/awc0086/tasks/awc0086_a

use library::lib::distance::is_within_euclidean_distance;

fn run(_n: usize, x: isize, y: isize, r: usize, xyp: Vec<(isize, isize, usize)>) -> usize {
    xyp.into_iter()
        .filter_map(|(x1, y1, p)| {
            is_within_euclidean_distance(x, y, x1, y1, r).then_some(p)
        })
        .sum()
}

