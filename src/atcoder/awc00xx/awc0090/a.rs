// https://atcoder.jp/contests/awc0090/tasks/awc0090_a

fn run(_n: usize, ab: Vec<(isize, isize)>) -> usize {
    ab.into_iter()
        .filter(|(a, b)| a > b)
        .map(|(a, b)| a - b)
        .sum::<isize>() as usize
}

#[cfg(test)]
mod tests {
    use super::*;

    struct TestCase(usize, Vec<(isize, isize)>, usize);

    #[test]
    fn awc0090_a() {
        let tests = [
            TestCase(3, vec![(10, 3), (5, 8), (7, 2)], 12),
            TestCase(3, vec![(3, 5), (2, 7), (1, 4)], 0),
            TestCase(10, vec![(100, 50), (30, 80), (200, 199), (15, 15), (500, 100), (60, 120), (45, 30), (90, 90), (300, 250), (10, 1000)], 516),
            TestCase(20, vec![(1000000000, 1), (999999999, 1000000000), (500000000, 400000000), (300000000, 300000001), (750000000, 250000000), (100, 200), (999999999, 999999998), (123456789, 987654321), (800000000, 100000000), (450000000, 450000000), (600000000, 500000000), (50000000, 90000000), (1, 1), (700000000, 650000000), (350000000, 400000000), (200000000, 100000000), (888888888, 111111111), (10, 10), (500000000, 500000001), (999999999, 2)], 4327777774),
            TestCase(1, vec![(1, 1000000000)], 0),
        ];

        for TestCase(n, ab, expected) in tests {
            assert_eq!(run(n, ab), expected);
        }
    }
}
